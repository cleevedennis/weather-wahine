"""Convert LINZ standard-port tide CSVs into tides-data.js for the page.

Download the yearly CSVs from LINZ, e.g.
  https://static.charts.linz.govt.nz/tide-tables/maj-ports/csv/Onehunga%202027.csv
save them in data/, then run:  python3 tools/linz_to_js.py data/Onehunga_*.csv

LINZ times are already local (NZST or NZDT as applicable).
"""
import csv, json, sys, os

def parse(path):
    events = []
    with open(path, encoding="utf-8-sig") as f:
        for r in csv.reader(f):
            if len(r) < 6 or not r[0].strip().isdigit() or not r[3].strip().isdigit():
                continue
            day, month, year = int(r[0]), int(r[2]), int(r[3])
            vals = [x.strip() for x in r[4:]]
            for i in range(0, len(vals) - 1, 2):
                t, h = vals[i], vals[i + 1]
                if t and h:
                    events.append([f"{year:04d}-{month:02d}-{day:02d}T{t}", float(h)])
    return events

def main(paths):
    port, events = None, []
    for p in sorted(paths):
        with open(p, encoding="utf-8-sig") as f:
            name = f.readline().split(",")[1].strip()
        if port and name != port:
            sys.exit(f"Mixed ports: {port} and {name}")
        port = name
        events += parse(p)
    events.sort()
    # label each extreme high or low by comparing with neighbours
    out = []
    for i, (t, h) in enumerate(events):
        nb = [events[j][1] for j in (i - 1, i + 1) if 0 <= j < len(events)]
        out.append([t, h, 1 if all(h > x for x in nb) else 0])
    js = ("// Generated by tools/linz_to_js.py from LINZ tide predictions (CC BY 4.0, Toitū Te Whenua LINZ).\n"
          f"// Standard port: {port}. Times are local NZ time. [time, height m, 1=high/0=low]\n"
          f"window.LINZ_TIDES = {json.dumps({'port': port, 'from': events[0][0][:10], 'to': events[-1][0][:10], 'events': out}, separators=(',', ':'))};\n")
    dest = os.path.join(os.path.dirname(__file__), "..", "tides-data.js")
    open(dest, "w").write(js)
    print(f"{port}: {len(out)} events {events[0][0]} → {events[-1][0]}, {os.path.getsize(dest)//1024} KB")

if __name__ == "__main__":
    main(sys.argv[1:])
